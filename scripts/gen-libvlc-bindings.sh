#!/usr/bin/env bash
# Regenerates libvlc-sys/src/bindings.rs from the pinned libVLC headers.
# Run after bumping VLC_COMMIT in build-libvlc.sh and rebuilding.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
bindgen=$root/vendor/tools/bin/bindgen
include=$root/vendor/vlc/include

if [ ! -x "$bindgen" ]; then
  cargo install -q --root "$root/vendor/tools" bindgen-cli --version 0.73.2 --locked
fi

"$bindgen" "$include/vlc/vlc.h" \
  --allowlist-function 'libvlc_.*' \
  --allowlist-type 'libvlc_.*' \
  --allowlist-var 'LIBVLC_.*|libvlc_.*' \
  --no-layout-tests --no-prepend-enum-name \
  --raw-line '// Generated by scripts/gen-libvlc-bindings.sh from the pinned libVLC 4 headers. Do not edit.' \
  -o "$root/libvlc-sys/src/bindings.rs" \
  -- -I"$include"

echo "wrote libvlc-sys/src/bindings.rs"
